/**
 * Lot 8I — scaffolds `.env.e2e.local` from the example without inventing secrets.
 * Prefills non-secret fields only. Never overwrites an existing file.
 * Never prints secret values.
 */
import { copyFileSync, existsSync, readFileSync, writeFileSync } from "node:fs"
import { randomInt } from "node:crypto"

function loadEnvFile(file) {
  const out = {}
  if (!existsSync(file)) return out
  for (const line of readFileSync(file, "utf8").split(/\r?\n/)) {
    const index = line.indexOf("=")
    if (index <= 0 || line.startsWith("#")) continue
    out[line.slice(0, index).trim()] = line.slice(index + 1).trim()
  }
  return out
}

const TARGET = ".env.e2e.local"
if (existsSync(TARGET)) {
  console.log("SKIP: .env.e2e.local already exists (refusing overwrite)")
  process.exit(0)
}

const local = loadEnvFile(".env.local")
const protect = local.NEXT_PUBLIC_SUPABASE_URL?.trim() || "https://YOUR_DEV_OR_PROD_PROJECT.supabase.co"
let protectHost = "YOUR_DEV_OR_PROD_PROJECT.supabase.co"
try {
  protectHost = new URL(protect).host
} catch {
  // keep placeholder
}

const prefix = `E2E-WOLOYEM-${Date.now()}${randomInt(100, 999)}`

const body = `# Generated by scripts/e2e-prepare-scaffold.mjs (Lot 8I)
# Fill E2E project URL + keys from a NEW Supabase project. Do not commit this file.
# Never point E2E_SUPABASE_* at the protected project (${protectHost}).

# App under test MUST use the E2E project during isolated runs.
NEXT_PUBLIC_APP_URL=http://localhost:3000
NEXT_PUBLIC_SUPABASE_URL=https://YOUR_E2E_PROJECT.supabase.co
NEXT_PUBLIC_SUPABASE_ANON_KEY=
SUPABASE_SERVICE_ROLE_KEY=

# Protected real/dev project — never seed this host.
E2E_PROTECT_SUPABASE_URL=${protect}

# Isolation markers (E2E_SUPABASE_URL must equal NEXT_PUBLIC_SUPABASE_URL above).
E2E_BASE_URL=http://localhost:3000
E2E_SUPABASE_URL=https://YOUR_E2E_PROJECT.supabase.co
E2E_SUPABASE_ANON_KEY=
E2E_SUPABASE_SERVICE_ROLE_KEY=

# Unique synthetic fixture prefix.
E2E_PREFIX=${prefix}

# Stripe: omit or sk_test_ only. sk_live_ blocks E2E.
# STRIPE_SECRET_KEY=
`

writeFileSync(TARGET, body, "utf8")
console.log("CREATED=.env.e2e.local")
console.log(`E2E_PROTECT_host=${protectHost}`)
console.log(`E2E_PREFIX=${prefix}`)
console.log("ACTION_REQUIRED=create dedicated Supabase E2E project and fill E2E + NEXT_PUBLIC keys")
